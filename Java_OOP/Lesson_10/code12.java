public class code12 {
     public static void main(String[] args){
        // while loop in java
        int i = 0;
        while(i < 5){
            System.out.println("The value of i is: " + i);
            i++;
        }
     
        // nested for loop in java
        for (int j = 0; j < 3; j++){
            for (int k = 0; k < 2; k++){
                System.out.println("The value of j is: " + j + " and the value of k is: " + k);
            }
        }
    }
}
