public class code5 {
   public static void main(String[] args) {
    // Assignment Operators
    int a = 10;
    a += 5; // a = a + 5
    System.out.println("Value of a after +=: " + a); // 15
    a -= 3; // a = a - 3
    System.out.println("Value of a after -=: " + a); // 12
    a *= 2; // a = a * 2
    System.out.println("Value of a after *=: " + a); // 24
    a /= 4; // a = a / 4
    System.out.println("Value of a after /=: " + a); // 6
    a %= 5; // a = a % 5
    System.out.println("Value of a after %=: " + a); // 1
   }
   }

   